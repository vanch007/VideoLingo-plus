def install_package(*packages):
    constraints = Path(__file__).resolve().parent / "constraints.txt"
    subprocess.check_call([sys.executable, "-m", "pip", "install", "-c", str(constraints), *packages])


def configure_ffmpeg_libraries():
    """Expose keg-only FFmpeg 7 libraries to macOS Python's native loader."""
    if platform.system() != "Darwin":
        return []
    library_dir = Path(sys.prefix) / "lib"
    sources = (Path("/opt/homebrew/opt/ffmpeg@7/lib"), Path("/usr/local/opt/ffmpeg@7/lib"))
    source = next((p for p in sources if p.is_dir()), None)
    if source is None:
        return []  # Conda's environment.yml can supply these libraries directly.
    library_dir.mkdir(parents=True, exist_ok=True)
    linked = []
    for path in sorted(source.glob("*.dylib")):
        if not re.fullmatch(r"lib(?:av\w+|swresample|swscale|postproc)\.\d+\.dylib", path.name):
            continue
        target = library_dir / path.name
        if os.path.lexists(target):
            continue  # Never replace a library already owned by this environment.
        target.symlink_to(path)
        linked.append(str(target))
    return linked


def install_runtime_dependencies():
    requirements = Path(__file__).resolve().parent / "requirements.txt"
    install_package("-r", str(requirements))
    configure_ffmpeg_libraries()
    subprocess.check_call([sys.executable, "-m", "pip", "check"])
    subprocess.check_call([sys.executable, "-c",
                           "import numpy, scipy.sparse.linalg, cv2, torch, torchaudio, torchvision, "
                           "torchcodec, spacy, librosa; import demucs.api"])

def check_nvidia_gpu():
    install_package("pynvml")
    import pynvml
    from translations.translations import translate as t
    try:
        pynvml.nvmlInit()
        device_count = pynvml.nvmlDeviceGetCount()
        if device_count > 0:
            print(t("Detected NVIDIA GPU(s)"))
            for i in range(device_count):
                handle = pynvml.nvmlDeviceGetHandleByIndex(i)
                name = pynvml.nvmlDeviceGetName(handle)
                print(f"GPU {i}: {name}")
            return True
        else:
            print(t("No NVIDIA GPU detected"))
            return False
    except pynvml.NVMLError:
        print(t("No NVIDIA GPU detected or NVIDIA drivers not properly installed"))
        return False
    finally:
        pynvml.nvmlShutdown()

def check_ffmpeg():
    from rich.console import Console
    from rich.panel import Panel
    from translations.translations import translate as t
    console = Console()

    try:
        # Check if ffmpeg is installed
        subprocess.run(['ffmpeg', '-version'], stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
        console.print(Panel(t("✅ FFmpeg is already installed"), style="green"))
        return True
    except (subprocess.CalledProcessError, FileNotFoundError):
        system = platform.system()
        install_cmd = ""
        
        if system == "Windows":
            install_cmd = "choco install ffmpeg"
            extra_note = t("Install Chocolatey first (https://chocolatey.org/)")
        elif system == "Darwin":
            install_cmd = "brew install ffmpeg"
            extra_note = t("Install Homebrew first (https://brew.sh/)")
        elif system == "Linux":
            install_cmd = "sudo apt install ffmpeg  # Ubuntu/Debian\nsudo yum install ffmpeg  # CentOS/RHEL"
            extra_note = t("Use your distribution's package manager")
        
        console.print(Panel.fit(
            t("❌ FFmpeg not found\n\n") +
            f"{t('🛠️ Install using:')}\n[bold cyan]{install_cmd}[/bold cyan]\n\n" +
            f"{t('💡 Note:')}\n{extra_note}\n\n" +
            f"{t('🔄 After installing FFmpeg, please run this installer again:')}\n[bold cyan]python install.py[/bold cyan]",
            style="red"
        ))
        raise SystemExit(t("FFmpeg is required. Please install it and run the installer again."))

